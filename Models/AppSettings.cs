using System.ComponentModel;
using System.Runtime.CompilerServices;

namespace Uttu.Models;

public class AppSettings : INotifyPropertyChanged
{
    private string _notificationTime = "08:30";
    private bool _autoGenerateDaily = true;
    private string _bufferMcpCommand = "internal"; // "internal" or path like "node Server/buffer-mcp.js"
    private string _bufferMcpArgs = "";
    private string _bufferAccessTokenEncrypted = string.Empty;
    private string _aiProvider = "Local Heuristic / Native Engine"; // "Local Heuristic / Native Engine", "OpenAI", "Anthropic Claude", "Google Gemini", "Ollama"
    private string _aiModel = "gpt-4o-mini";
    private string _aiApiKeyEncrypted = string.Empty;
    private string _ollamaEndpoint = "http://localhost:11434";
    private string _cardTheme = "Dark";
    private bool _closeToTray = true;
    private string _defaultAuthorHandle = "@user";
    private string _defaultAuthorName = "Founder / Builder";

    public string NotificationTime
    {
        get => _notificationTime;
        set => SetField(ref _notificationTime, value);
    }

    public bool AutoGenerateDaily
    {
        get => _autoGenerateDaily;
        set => SetField(ref _autoGenerateDaily, value);
    }

    public string BufferMcpCommand
    {
        get => _bufferMcpCommand;
        set => SetField(ref _bufferMcpCommand, value);
    }

    public string BufferMcpArgs
    {
        get => _bufferMcpArgs;
        set => SetField(ref _bufferMcpArgs, value);
    }

    public string BufferAccessTokenEncrypted
    {
        get => _bufferAccessTokenEncrypted;
        set => SetField(ref _bufferAccessTokenEncrypted, value);
    }

    public string AiProvider
    {
        get => _aiProvider;
        set => SetField(ref _aiProvider, value);
    }

    public string AiModel
    {
        get => _aiModel;
        set => SetField(ref _aiModel, value);
    }

    public string AiApiKeyEncrypted
    {
        get => _aiApiKeyEncrypted;
        set => SetField(ref _aiApiKeyEncrypted, value);
    }

    public string OllamaEndpoint
    {
        get => _ollamaEndpoint;
        set => SetField(ref _ollamaEndpoint, value);
    }

    public string CardTheme
    {
        get => _cardTheme;
        set => SetField(ref _cardTheme, value);
    }

    public bool CloseToTray
    {
        get => _closeToTray;
        set => SetField(ref _closeToTray, value);
    }

    public string DefaultAuthorHandle
    {
        get => _defaultAuthorHandle;
        set => SetField(ref _defaultAuthorHandle, value);
    }

    public string DefaultAuthorName
    {
        get => _defaultAuthorName;
        set => SetField(ref _defaultAuthorName, value);
    }

    public event PropertyChangedEventHandler? PropertyChanged;

    protected void OnPropertyChanged([CallerMemberName] string? propertyName = null)
    {
        PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(propertyName));
    }

    protected bool SetField<T>(ref T field, T value, [CallerMemberName] string? propertyName = null)
    {
        if (EqualityComparer<T>.Default.Equals(field, value)) return false;
        field = value;
        OnPropertyChanged(propertyName);
        return true;
    }
}
