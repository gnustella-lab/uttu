using System.Diagnostics;
using System.Windows.Threading;
using Uttu.Models;

namespace Uttu.Services;

public class ProactiveSchedulerService
{
    private readonly DatabaseService _db;
    private readonly IdeaGeneratorService _generator;
    private readonly ToastNotificationService _toast;
    private readonly DispatcherTimer _timer;
    private DateTime? _lastRunDate;
    private AppSettings _settings = new();

    public event Action<List<PostDraft>>? OnNewDraftsGenerated;
    public string NextRunFormatted { get; private set; } = "08:30 (Amanhã)";

    public ProactiveSchedulerService(DatabaseService db, IdeaGeneratorService generator, ToastNotificationService toast)
    {
        _db = db;
        _generator = generator;
        _toast = toast;

        _timer = new DispatcherTimer
        {
            Interval = TimeSpan.FromSeconds(30)
        };
        _timer.Tick += async (s, e) => await CheckScheduleAsync();
    }

    public void Start(AppSettings settings)
    {
        _settings = settings;
        UpdateNextRunDisplay();
        _timer.Start();
    }

    public void UpdateSettings(AppSettings settings)
    {
        _settings = settings;
        UpdateNextRunDisplay();
    }

    public async Task<List<PostDraft>> TriggerNowAsync()
    {
        return await ExecuteGenerationPipelineAsync();
    }

    private async Task CheckScheduleAsync()
    {
        if (!_settings.AutoGenerateDaily) return;

        var now = DateTime.Now;
        if (TimeSpan.TryParse(_settings.NotificationTime, out var targetTime))
        {
            // Check if current time is within 1 minute of target time and hasn't run today
            if (now.TimeOfDay >= targetTime && now.TimeOfDay < targetTime.Add(TimeSpan.FromMinutes(2)))
            {
                if (_lastRunDate == null || _lastRunDate.Value.Date != now.Date)
                {
                    _lastRunDate = now;
                    await ExecuteGenerationPipelineAsync();
                }
            }
        }

        UpdateNextRunDisplay();
    }

    private async Task<List<PostDraft>> ExecuteGenerationPipelineAsync()
    {
        Debug.WriteLine("[ProactiveSchedulerService] Disparando pipeline proativo de ideação...");

        var memories = await _db.GetActiveMemoriesAsync();
        var voice = await _db.GetVoiceProfileAsync();

        var drafts = await _generator.GenerateBatchAsync(memories, voice, _settings);

        foreach (var draft in drafts)
        {
            await _db.SavePostAsync(draft);
        }

        // Emite Toast Notification no Windows 10 Action Center
        _toast.ShowDraftsReadyToast(drafts);

        OnNewDraftsGenerated?.Invoke(drafts);
        UpdateNextRunDisplay();

        return drafts;
    }

    private void UpdateNextRunDisplay()
    {
        if (TimeSpan.TryParse(_settings.NotificationTime, out var targetTime))
        {
            var now = DateTime.Now;
            if (now.TimeOfDay < targetTime)
            {
                NextRunFormatted = $"Hoje às {_settings.NotificationTime}";
            }
            else
            {
                NextRunFormatted = $"{_settings.NotificationTime} (Amanhã)";
            }
        }
        else
        {
            NextRunFormatted = $"{_settings.NotificationTime}";
        }
    }
}
